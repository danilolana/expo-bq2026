export function validateQuestionBank(bank: readonly Question[]): void {
  const ids = new Set(bank.map((question) => question.id))
  const techCount = bank.filter((question) => question.category === 'informatica').length
  const generalCount = bank.filter((question) => question.category === 'geral').length
  const hasInvalidAnswer = bank.some(
    (question) =>
      question.options.length !== 4 ||
      question.correctAnswer < 0 ||
      question.correctAnswer >= question.options.length,
  )

  if (
    bank.length !== 70 ||
    ids.size !== bank.length ||
    techCount !== 25 ||
    generalCount !== 45 ||
    hasInvalidAnswer
  ) {
    throw new Error('Banco de perguntas inválido: verifique contagens, IDs e respostas.')
  }
}

